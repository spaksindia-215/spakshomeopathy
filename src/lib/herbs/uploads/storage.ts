import { mkdir, writeFile, unlink } from 'fs/promises';
import path from 'path';
import { getAppConfig } from '@/lib/env';
import {
  HERBS_UPLOAD_SUBDIR,
  extensionForType,
  validateUploadFile,
  type AllowedImageType,
} from './config';

export interface SavedUpload {
  /** Bare filename as stored on disk — this is what gets saved into
   * `HerbProductDoc.image`, matching the existing app's convention of
   * storing filenames (not full paths) in the database (blueprint
   * R-13/P-13 — product-detail JS parses a fixed URL segment index, so
   * every image lives at a predictable `/uploaded_files/<subdir>/<name>`
   * shape). */
  filename: string;
  /** Full public URL path, ready to use directly in an <img src>. */
  publicPath: string;
}

function sanitizeBaseName(originalName: string): string {
  const base = path.basename(originalName, path.extname(originalName));
  return (
    base
      .toLowerCase()
      .replace(/[^a-z0-9]+/g, '-')
      .replace(/^-+|-+$/g, '')
      .slice(0, 60) || 'image'
  );
}

/**
 * Resolves `UPLOAD_DIR` (`@/lib/env`'s `getAppConfig().uploadDir`)
 * against `process.cwd()` — using `path.resolve`, not `path.join`.
 * `path.join(cwd, uploadDir)` would silently concatenate an ABSOLUTE
 * `UPLOAD_DIR` onto `cwd` instead of using it as-is (`path.join('/a',
 * '/b')` → `'/a/b'`, not `'/b'` — confirmed directly), which would
 * quietly write uploads to the wrong location for any deployment that
 * configures `UPLOAD_DIR` as an absolute path. `path.resolve` handles
 * both relative and absolute `uploadDir` values correctly.
 */
function resolveHerbsUploadDir(): string {
  const { uploadDir } = getAppConfig();
  return path.resolve(process.cwd(), uploadDir, HERBS_UPLOAD_SUBDIR);
}

/**
 * Saves an uploaded product image to disk under
 * `<UPLOAD_DIR>/herbs/`, using the same `<unixTimestamp>g<name>`
 * filename convention the rest of this app's `uploaded_files/*`
 * directories already use (visible directly in
 * `public/uploaded_files/products/*` — e.g. `1672657141gRhus-tox.png`),
 * so this fits the existing asset convention rather than inventing a new
 * one, even though no code previously wrote files this way.
 *
 * Returns validation errors as a typed result rather than throwing —
 * same graceful, explicit-reason convention as
 * `@/lib/herbs/db/service`/`@/lib/herbs/orders/service`.
 */
export async function saveHerbImageUpload(
  file: File
): Promise<{ ok: true; upload: SavedUpload } | { ok: false; reason: string }> {
  const validationError = validateUploadFile(file);
  if (validationError) {
    return { ok: false, reason: validationError.message };
  }

  const extension = extensionForType(file.type as AllowedImageType);
  const safeName = sanitizeBaseName(file.name);
  const filename = `${Date.now()}g${safeName}.${extension}`;

  // `resolveHerbsUploadDir()` calls `getAppConfig()`, which throws if
  // APP_URL/UPLOAD_DIR's fallback env reads are missing — kept inside
  // this try block (not resolved above it) so a misconfigured
  // environment degrades to the same typed `{ ok: false, reason }`
  // result as every other failure here, instead of throwing uncaught
  // out of the Server Action that calls this.
  let targetDir: string;
  let targetPath: string;
  try {
    targetDir = resolveHerbsUploadDir();
    targetPath = path.join(targetDir, filename);
    await mkdir(targetDir, { recursive: true });
    const bytes = Buffer.from(await file.arrayBuffer());
    await writeFile(targetPath, bytes);
  } catch (err) {
    return {
      ok: false,
      reason: err instanceof Error ? `Failed to save file: ${err.message}` : 'Failed to save file.',
    };
  }

  return {
    ok: true,
    upload: {
      filename,
      publicPath: `/uploaded_files/${HERBS_UPLOAD_SUBDIR}/${filename}`,
    },
  };
}

/** Best-effort cleanup — e.g. when a new image replaces an old one on
 * edit. Failure is swallowed (logged, not thrown): a stray orphaned file
 * is a minor disk-space concern, not something that should block saving
 * the product record itself.
 *
 * `filename` is always machine-generated by `saveHerbImageUpload` above
 * (a timestamp + sanitized name + extension, never raw user input) in
 * every call site this app has — but this function accepts a plain
 * string, so it defensively re-validates that the resolved path stays
 * inside the herbs upload directory before unlinking, rather than
 * trusting that invariant to hold at every future call site too. */
export async function deleteHerbImageUpload(filename: string): Promise<void> {
  try {
    const targetDir = resolveHerbsUploadDir();
    const targetPath = path.join(targetDir, path.basename(filename));

    if (!targetPath.startsWith(targetDir + path.sep)) {
      return; // Would escape the herbs upload directory — refuse silently.
    }

    await unlink(targetPath);
  } catch {
    // Not found, already removed, or environment misconfigured
    // (getAppConfig() threw) — this is a best-effort cleanup, so any
    // failure here is swallowed rather than propagated. See this
    // function's own doc comment above.
  }
}
