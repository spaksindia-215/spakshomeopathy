/**
 * Order-cancellation token — the Next.js equivalent of Laravel's
 * `encrypt($row->GroupId)` / `decrypt($req->cncl_id)`
 * (`manage-orders.blade.php`'s cancel link, `BuyerController::CancelOrder`).
 *
 * SOURCE EQUIVALENCE, NOT BYTE COMPATIBILITY
 * -------------------------------------------
 * Laravel's `encrypt()`/`decrypt()` use `APP_KEY` with Laravel's own
 * proprietary AES-256-CBC + HMAC payload format (a base64 JSON envelope
 * with `iv`/`value`/`mac` keys) — reproducing that format byte-for-byte
 * would mean re-implementing Laravel's `Illuminate\Encryption\Encrypter`
 * class, a materially separate undertaking with no actual payoff here:
 * this token is never decrypted BY Laravel and no Laravel-produced
 * ciphertext is ever decrypted BY this app — it is generated by
 * `manage-orders/page.tsx` and consumed by `cancel-order/route.ts`
 * WITHIN THIS SAME APPLICATION, in the same request/response cycle
 * pattern `session.ts` already established for the session cookie
 * ("a distinct mechanism achieving the same authorization outcome, not a
 * decoder for Laravel's own format"). Same precedent applied here.
 *
 * SECURITY PROPERTY PRESERVED: the token must be (a) opaque — a viewer
 * cannot read the underlying GroupId off the URL, and (b) tamper-evident —
 * changing so much as one character must make it unusable. AES-256-GCM
 * (authenticated encryption) provides both properties directly: GCM's
 * built-in auth tag makes tampering detectable (decryption throws), and
 * the ciphertext itself is opaque without the key. This is a STRONGER
 * guarantee than Laravel's own CBC+HMAC construction requires, not a
 * weaker one — no fidelity is lost by not matching CBC exactly.
 *
 * KEY: reuses the existing `SESSION_SECRET` (via `getCryptoConfig()`,
 * already required/validated elsewhere) rather than introducing a new
 * environment variable — consistent with the M4 task boundary's "do not
 * add unrelated features" / minimal-surface discipline. `SESSION_SECRET`
 * is a raw string; `scryptSync` derives a fixed 32-byte AES key from it
 * (a cheap, deterministic per-process derivation — not a password-storage
 * KDF, no timing-sensitive use case here) so the same secret already
 * governing session-cookie integrity also governs this token, with no new
 * secret to provision, disclose, or accidentally log.
 */

import { createCipheriv, createDecipheriv, randomBytes, scryptSync } from 'crypto';
import { getCryptoConfig } from '../env';

const ALGORITHM = 'aes-256-gcm';
const IV_LENGTH = 12; // GCM's recommended IV length
const KEY_SALT = 'spaks-order-cancel-token-v1'; // fixed, non-secret salt — see header

function deriveKey(): Buffer {
  const { sessionSecret } = getCryptoConfig();
  return scryptSync(sessionSecret, KEY_SALT, 32);
}

/** Mirrors `encrypt($row->GroupId)` — produces an opaque, tamper-evident,
 * URL-safe token carrying one GroupId. */
export function encryptGroupId(groupId: number): string {
  const key = deriveKey();
  const iv = randomBytes(IV_LENGTH);
  const cipher = createCipheriv(ALGORITHM, key, iv);
  const encrypted = Buffer.concat([cipher.update(String(groupId), 'utf-8'), cipher.final()]);
  const authTag = cipher.getAuthTag();
  return Buffer.concat([iv, authTag, encrypted]).toString('base64url');
}

/**
 * Mirrors `decrypt($req->cncl_id)` — returns the original GroupId, or
 * `null` on ANY failure (missing, malformed, tampered, or wrong-key
 * ciphertext). Laravel's `decrypt()` THROWS a `DecryptException` on
 * failure, which — uncaught, and with `APP_DEBUG=true` in source
 * (verified directly this session) — currently renders a raw debug
 * stack-trace page on real Laravel for a missing/invalid `cncl_id`. This
 * function does not reproduce a stack trace (there is no Next.js
 * equivalent worth building, and no observable behavior of VALUE to
 * preserve in a debug crash page — see the same reasoning `orderService.ts`
 * already applied to B-12 itself); the caller (`cancel-order/route.ts`)
 * treats `null` as "reject this request," a clean equivalent outcome
 * (request denied) without the crash's literal presentation.
 */
export function decryptGroupId(token: string): number | null {
  try {
    const raw = Buffer.from(token, 'base64url');
    if (raw.length < IV_LENGTH + 16) return null; // too short to contain iv + authTag
    const iv = raw.subarray(0, IV_LENGTH);
    const authTag = raw.subarray(IV_LENGTH, IV_LENGTH + 16);
    const encrypted = raw.subarray(IV_LENGTH + 16);

    const key = deriveKey();
    const decipher = createDecipheriv(ALGORITHM, key, iv);
    decipher.setAuthTag(authTag);
    const decrypted = Buffer.concat([decipher.update(encrypted), decipher.final()]).toString(
      'utf-8'
    );

    const groupId = Number(decrypted);
    if (!Number.isInteger(groupId)) return null;
    return groupId;
  } catch {
    // Any crypto failure (bad auth tag = tampered, malformed base64, etc.)
    // — never throws to the caller, matches decrypt()'s FAILURE OUTCOME
    // (reject) without matching its literal exception-based mechanism.
    return null;
  }
}
